"""Generate src/jem/envs/mikasa_primitives.py from the pinned MIKASA hard-battery planner.

The upstream planner (MIT license) defines its motion primitives as closures inside
main(). This script copies that block verbatim into make_primitives(env, max_env_steps)
so the BatteriesSort collector reuses upstream-tested pick/insert/extract/place/press
code instead of a rewrite. It refuses a source whose SHA-256 differs from the pin.
"""
from pathlib import Path
import hashlib, json, sys

ROOT = Path(__file__).resolve().parents[1]
REL = "mikasa_robo_suite/vla/utils/motion_planning/motion_planning_batteries_checker_hard.py"
OUT = ROOT / "src/jem/envs/mikasa_primitives.py"
START = "    base_pose = env_u.agent.robot.pose\n"
STOP = "    open_gripper_safe(t=2)\n\n    num_batteries"


def main(source_root=ROOT / "third_party/mikasa"):
    src = Path(source_root) / REL
    text = src.read_text()
    digest = hashlib.sha256(text.encode()).hexdigest()
    pins = json.loads((ROOT / "third_party/revisions.json").read_text())["files"]
    expected = pins.get(f"third_party/mikasa/{REL}")
    if expected and digest != expected:
        raise SystemExit(f"Planner hash {digest} != pinned {expected}")
    header, rest = text.split("def parse_args():", 1)
    # IPython is only used for notebook video display upstream.
    header = header.replace("from IPython.display import Video\n", "")
    header = header.replace('sys.path.append(os.path.abspath(os.path.join(os.path.dirname(__file__), "../../../..")))\n', "")
    a, b = rest.index(START), rest.index(STOP)
    body = rest[a:b]
    revision = json.loads((ROOT / "third_party/revisions.json").read_text())["mikasa"]["revision"]
    OUT.write_text(
        f'"""GENERATED by scripts/build_planner_primitives.py from MIKASA-Robo {revision}\n'
        f"{REL} (sha256 {digest}). MIT License, Copyright (c) 2026 CognitiveAISystems.\n"
        'Do not edit by hand; regenerate instead."""\n'
        "# flake8: noqa\n"
        + header
        + "def make_primitives(env, max_env_steps):\n"
        "    env_u = env.unwrapped\n"
        + body
        + "    return types.SimpleNamespace(**{k: v for k, v in locals().items() if not k.startswith('_')})\n"
    )
    print(f"wrote {OUT.relative_to(ROOT)} ({len(body.splitlines())} upstream lines)")


if __name__ == "__main__":
    main(*sys.argv[1:])
